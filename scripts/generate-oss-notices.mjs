/**
 * One-time generator for the open-source credits list shown in Settings →
 * Privacy & Terms (v0.8.7). Run manually after adding or upgrading a
 * dependency:
 *
 *   node scripts/generate-oss-notices.mjs
 *
 * Reads `package-lock.json` (the only file that already lists every
 * installed package's resolved version and license) and writes
 * `src/app/oss-notices.generated.ts` — a plain data file `legal-content.ts`
 * imports. Not run by `npm run check`: keeping it exactly in sync on every
 * install is a CI rule with real maintenance cost and no user-facing failure
 * mode (architecture-expert, v0.8.7 spec) — a stale list is wrong, not
 * broken, and gets caught the next time this script runs.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))

const lock = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8'))
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))

/** @type {Map<string, { version: string; license: string }>} */
const packages = new Map()
for (const [key, meta] of Object.entries(lock.packages ?? {})) {
  if (!key.startsWith('node_modules/')) continue // skip the root package itself
  const name = key.slice('node_modules/'.length)
  if (name.startsWith('.bin/')) continue
  // A package we ship from our own folder (`file:vendor/...`, v0.9.27: the patched Signalsmith Stretch) is a link in the lock file;
  // its version and license live on the folder's own entry. Skipping the link would drop a shipped component from the credits.
  const own = meta?.link && meta.resolved ? lock.packages[meta.resolved] : meta
  if (!own?.version) continue
  packages.set(name, { version: own.version, license: own.license ?? 'unknown' })
}

const notices = [...packages.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([name, { version, license }]) => ({ name, version, license }))

const unknownLicense = notices.filter((n) => n.license === 'unknown')

const banner =
  '// Generated by scripts/generate-oss-notices.mjs from package-lock.json — do not edit by hand.\n' +
  `// Regenerate after adding or upgrading a dependency. ${notices.length} packages as of soundgrid@${pkg.version}.\n`

const body =
  `export interface OssNotice {\n  name: string\n  version: string\n  license: string\n}\n\n` +
  `export const OSS_NOTICES: OssNotice[] = ${JSON.stringify(notices, null, 2)}\n`

writeFileSync(join(ROOT, 'src/app/oss-notices.generated.ts'), banner + '\n' + body)

console.log(`Wrote ${notices.length} packages to src/app/oss-notices.generated.ts`)
if (unknownLicense.length > 0) {
  console.log(
    `${unknownLicense.length} package(s) have no license field in package-lock.json: ` +
      unknownLicense.map((n) => n.name).join(', '),
  )
}
